import express, { Request, Response, NextFunction } from 'express';
import cors from 'cors';
import path from 'path';
import fs from 'fs';
import routes from './routes/courseRoutes';
const app = express();
app.use(cors({origin:process.env.WEB_ORIGIN || 'http://localhost:3000'}));
app.use(express.json({limit:'2mb'}));
const uploadDir = path.resolve(__dirname, '../uploads');
fs.mkdirSync(uploadDir,{recursive:true});
app.use('/uploads', express.static(uploadDir));
app.use('/uploads', express.static(path.resolve(__dirname, '../../../uploads')));
app.use('/image', express.static(path.resolve(__dirname, '../../../image')));
app.use('/api', routes);
app.use((err: Error & {status?:number},_req:Request,res:Response,_next:NextFunction)=>{console.error(err.message);res.status(err.status || 500).json({message:err.status ? err.message : 'เกิดข้อผิดพลาดในการเชื่อมต่อหรือประมวลผลข้อมูล'})});
export default app;
